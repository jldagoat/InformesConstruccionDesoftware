
public class Ejercicio37 {
    public static void main(String[] args) {
        double angulo1 = 0;
        double angulo2 = 60;
        double angulo3 = 180;

        System.out.println("Coseno de 0 grados: " + Math.cos(Math.toRadians(angulo1)));
        System.out.println("Coseno de 60 grados: " + Math.cos(Math.toRadians(angulo2)));
        System.out.println("Coseno de 180 grados: " + Math.cos(Math.toRadians(angulo3)));
    }
}
