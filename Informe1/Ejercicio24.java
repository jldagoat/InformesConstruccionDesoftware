
public class Ejercicio24 {
    public static void main(String[] args) {
        boolean verdadero = true;
        boolean falso = false;

        System.out.println("AND: " + (verdadero && falso));
        System.out.println("OR: " + (verdadero || falso));
        System.out.println("NOT: " + (!verdadero));
        System.out.println("XOR: " + (verdadero ^ falso));
        System.out.println("AND simple: " + (verdadero & falso));
        System.out.println("OR simple: " + (verdadero | falso));
    }
}
