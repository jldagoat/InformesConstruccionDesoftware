
public class Ejercicio22 {
    public static void main(String[] args) {
        int numero = 20;

        System.out.println("Valor inicial: " + numero);

        numero += 5;
        System.out.println("Suma combinada: " + numero);

        numero -= 10;
        System.out.println("Resta combinada: " + numero);

        numero *= 2;
        System.out.println("Multiplicacion combinada: " + numero);

        numero /= 3;
        System.out.println("Division combinada: " + numero);

        numero %= 4;
        System.out.println("Modulo combinado: " + numero);
    }
}
