
public class Ejercicio23 {
    public static void main(String[] args) {
        int numero1 = 10;
        int numero2 = 5;

        System.out.println("Numero 1: " + numero1);
        System.out.println("Numero 2: " + numero2);

        System.out.println("Igual que: " + (numero1 == numero2));
        System.out.println("Diferente que: " + (numero1 != numero2));
        System.out.println("Mayor que: " + (numero1 > numero2));
        System.out.println("Menor que: " + (numero1 < numero2));
        System.out.println("Mayor o igual que: " + (numero1 >= numero2));
        System.out.println("Menor o igual que: " + (numero1 <= numero2));
    }
}
